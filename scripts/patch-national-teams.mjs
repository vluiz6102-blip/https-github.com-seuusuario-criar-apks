import { copyFileSync, readFileSync, writeFileSync, mkdirSync, appendFileSync } from "node:fs";
import { dirname, resolve } from "node:path";

const root = process.cwd();
const game = resolve(root, "game-source");
const web = resolve(game, "web");
const src = resolve(web, "src");

function replaceOnce(file, oldText, newText) {
  const original = readFileSync(file, "utf8");
  const count = original.split(oldText).length - 1;
  if (count !== 1) throw new Error("Expected one patch target in " + file + ", found " + count + ": " + oldText.slice(0, 100));
  writeFileSync(file, original.replace(oldText, newText), "utf8");
}

copyFileSync(resolve(root, "data/worldcup2026-squads.json"), resolve(src, "worldcup2026-squads.json"));
copyFileSync(resolve(root, "mobile-overlay/nationalTeams.ts"), resolve(src, "nationalTeams.ts"));
copyFileSync(resolve(root, "mobile-overlay/GandulaSplash.tsx"), resolve(src, "components/GandulaSplash.tsx"));
copyFileSync(resolve(root, "mobile-overlay/NationalTeamCareerView.tsx"), resolve(src, "components/NationalTeamCareerView.tsx"));

const teamsPath = resolve(src, "teams.ts");
replaceOnce(
  teamsPath,
  'import type { Team } from "./types";',
  'import type { Team } from "./types";\nimport { NATIONAL_TEAMS } from "./nationalTeams";',
);
replaceOnce(
  teamsPath,
  'return ALL_TEAMS.find((t) => t.id === id);',
  'return ALL_TEAMS.find((t) => t.id === id) ?? NATIONAL_TEAMS.find((t) => t.id === id);',
);

const seasonPath = resolve(src, "components/SeasonView.tsx");
replaceOnce(
  seasonPath,
  'import FriendlyMatchView from "./FriendlyMatchView";',
  'import FriendlyMatchView from "./FriendlyMatchView";\nimport NationalTeamCareerView from "./NationalTeamCareerView";',
);
replaceOnce(
  seasonPath,
  '  | { tag: "fired"; career: Career; finalBalance: number }\n  | { tag: "friendly" };',
  '  | { tag: "fired"; career: Career; finalBalance: number }\n  | { tag: "friendly" }\n  | { tag: "national"; teamId: number };',
);
replaceOnce(
  seasonPath,
  '  const careerTeamName =\n    "career" in phase\n      ? teamById(phase.career.controlledTeamId)?.name ?? null\n      : null;',
  '  const careerTeamName =\n    "career" in phase\n      ? teamById(phase.career.controlledTeamId)?.name ?? null\n      : phase.tag === "national"\n        ? teamById(phase.teamId)?.name ?? null\n        : null;',
);
replaceOnce(
  seasonPath,
  '          <GandulaSplash\n            onStart={run}\n            onFriendly={openFriendly}\n          />',
  '          <GandulaSplash\n            onStart={run}\n            onStartNation={(teamId) => setPhase({ tag: "national", teamId })}\n            onFriendly={openFriendly}\n          />',
);
replaceOnce(
  seasonPath,
  '      case "friendly":\n        return <FriendlyMatchView onBack={backFromFriendly} />;',
  '      case "national":\n        return (\n          <NationalTeamCareerView\n            teamId={phase.teamId}\n            onBack={() => setPhase({ tag: "form" })}\n            onStatus={onStatus}\n          />\n        );\n      case "friendly":\n        return <FriendlyMatchView onBack={backFromFriendly} />;',
);

